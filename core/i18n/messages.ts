const messages: Record<
  SupportedLocale,
  Record<MessageKey, string>
> = {
  "es-419": esMessages,
  "en-US": enMessages,
  "pt-BR": ptMessages,
  "fr-FR": frMessages,
};

export function translate(
  locale: SupportedLocale,
  key: MessageKey,
  params: MessageParams = {}
): string {
  const template =
    messages[locale]?.[key] ??
    esMessages[key];

  return template.replace(
    /\{(\w+)\}/g,
    (match, name: string) =>
      params[name] === undefined
        ? match
        : String(params[name])
  );
}
